// Renders every journey's itinerary PDF at build time into lib/itineraryPdfs.generated.mjs (git-ignored).
// Runs before `next dev` and `next build`. The gated /api/itinerary/[slug] route serves these bytes,
// so @react-pdf/renderer (pdfkit, fontkit, yoga) never ships in the server bundle. That keeps the
// Cloudflare Worker under the 3 MiB Free-plan limit and avoids pdfkit's runtime font loading,
// which can't resolve inside a Worker.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";

const root = process.cwd();
const cacheDir = path.join(root, "node_modules/.cache/itineraries");
const bundle = path.join(cacheDir, "render.mjs");
const out = path.join(root, "lib/itineraryPdfs.generated.mjs");

await mkdir(cacheDir, { recursive: true });
await build({
  stdin: {
    contents: `
      import { createElement } from "react";
      import { renderToBuffer } from "@react-pdf/renderer";
      import { journeys } from "@/data/journeys";
      import { ItineraryDocument } from "@/components/pdf/ItineraryDocument";
      export { journeys };
      export const render = (j) => renderToBuffer(createElement(ItineraryDocument, { j }));
    `,
    resolveDir: root,
    loader: "tsx",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  jsx: "automatic",
  // Keep packages in node_modules so pdfkit loads its standard fonts the Node way.
  packages: "external",
  tsconfig: path.join(root, "tsconfig.json"),
  outfile: bundle,
  logLevel: "warning",
});

const { journeys, render } = await import(`${pathToFileURL(bundle).href}?t=${Date.now()}`);
const entries = [];
for (const j of journeys) {
  const pdf = await render(j);
  entries.push(`  ${JSON.stringify(j.slug)}: ${JSON.stringify(Buffer.from(pdf).toString("base64"))},`);
}
await writeFile(
  out,
  `// Generated by scripts/build-itineraries.mjs. Do not edit.\n/** Itinerary PDFs by journey slug, base64-encoded. */\nexport const itineraryPdfs = {\n${entries.join("\n")}\n};\n`,
);
console.log(`itineraries: ${entries.length} PDFs rendered`);
